"""Модуль виртуальных анализаторов качества (ВАК / Soft Sensors).

Реализует 17 расчетных моделей для оперативной оценки свойств потоков
установок ЭЛОУ-АВТ-6 и 24-2000 без ожидания лабораторных анализов LIMS.
Исправлены опечатки оригинального ТЗ (включая скобки в знаменателе CFPP).
"""

from __future__ import annotations

import math
from typing import Dict, Any


class VakCalculator:
    """
    Вычисление 17 виртуальных анализаторов качества (ВАК) на основе сырых тегов КИПиА
    и данных LIMS (для авторегрессионной коррекции).
    """

    @staticmethod
    def calculate(tags: Dict[str, Any]) -> Dict[str, float]:
        """
        Рассчитывает 17 показателей качества по текущим значениям тегов.

        :param tags: Словарь КИПиА и LIMS тегов (например, {"F30": 120.5, "T33": 110.2, ...})
        :return: Словарь расчетных параметров ВАК
        """
        vak: Dict[str, float] = {}

        def get(tag_name: str, default: float = 0.0) -> float:
            """Безопасное извлечение числового значения тега."""
            val = tags.get(tag_name, default)
            if val is None:
                return default
            try:
                num = float(val)
                return default if (math.isnan(num) or math.isinf(num)) else num
            except (ValueError, TypeError):
                return default

        # =========================================================================
        # 1. ЭЛОУ-АВТ-6: Фракция 240-350 °C (Дизельный дистиллят)
        # =========================================================================
        try:
            # Плотность D15
            f30, f32 = get("F30"), get("F32")
            denom_1 = f32 + f30
            f_ratio_1 = f30 / denom_1 if denom_1 != 0.0 else 0.0
            vak["AVT6:240-350:D15"] = (
                791.22872 - 5.30294 * f_ratio_1 + 0.52755 * get("T66") - 0.15629 * get("T33")
            )

            # Температура 50% выкипания (T50)
            vak["AVT6:240-350:T50"] = (
                283.177
                - 0.01685 * get("F7")
                + 0.06248 * get("F30")
                + 0.22048 * get("F34")
                - 0.25816 * get("F45")
                - 0.12159 * get("F59")
                + 0.01221 * get("F63")
            )

            # Конец кипения (EBP)
            vak["AVT6:240-350:EBP"] = (
                813.883
                + 2.66463 * get("F30")
                - 0.20239 * get("T33")
                - 3.65888 * get("F36")
                - 14.08235 * get("T37")
                - 1.32603 * get("T40")
                + 14.60206 * get("T58")
            )

            # Предельная температура фильтруемости (CFPP)
            # Исправлена опечатка формулы ТЗ: (F65/(F32+F30))
            f65 = get("F65")
            f_ratio_2 = f65 / denom_1 if denom_1 != 0.0 else 0.0
            vak["AVT6:240-350:CFPP"] = (
                31.40363
                - 0.06784 * get("T33")
                + 17.411 * get("P67")
                - 8.11544 * get("P4")
                - 0.47309 * f_ratio_2
            )
        except Exception:
            pass

        # =========================================================================
        # 2. ЭЛОУ-АВТ-6: Фракция >350 °C (Мазут / Вакуумный газойль)
        # =========================================================================
        try:
            f31, f57 = get("F31"), get("F57")
            f_ratio_3 = f31 / f57 if f57 != 0.0 else 0.0

            # Температура 50% выкипания
            vak["AVT6:350:T50"] = (
                981.06539 + 0.27467 * get("T42") - 0.32983 * f_ratio_3 - 0.49014 * get("T48")
            )

            # Выход фракции I350
            vak["AVT6:350:I350"] = (
                39.562
                - 1.62865 * get("L43")
                - 0.76664 * get("T6")
                - 0.22361 * get("T18")
                + 0.00031 * get("F64") * (get("T15") - get("T11"))
            )

            # Плотность D15
            vak["AVT6:350:D15"] = (
                983.092 + 0.27467 * get("T42") - 0.49014 * get("T48") - 0.32983 * f_ratio_3
            )

            # Предельная температура фильтруемости (CFPP)
            vak["AVT6:350:CFPP"] = (
                19.27111 - 0.10582 * get("T48") + 0.13836 * get("T40") - 0.42304 * f_ratio_3
            )

            # Кинематическая вязкость (ViscosityK)
            vak["AVT6:350-500:ViscosityK"] = (
                5.831
                + 0.00976 * get("T6")
                + 0.01188 * get("T13")
                + 0.00224 * get("T18")
                + 0.01905 * get("T20")
                + 0.00794 * get("L43")
                - 0.02496 * get("T48")
                - 0.00008 * get("P50")
                - 0.00882 * get("F53")
                - 0.00394 * get("P51")
                - 0.00255 * get("F59")
                + 0.01153 * get("T61")
            )
        except Exception:
            pass

        # =========================================================================
        # 3. Установка 24-2000: Стабильный гидрогенизат (ГО ДТ)
        # =========================================================================
        try:
            f1, f26 = get("F1"), get("F26")
            f_ratio_4 = f1 / f26 if f26 != 0.0 else 0.0

            # Температура 90% выкипания
            vak["24-2000:GODT:T90"] = (
                162.998
                + 0.12945 * get("T12")
                + 59.57 * get("F15")
                + 0.00036 * get("W7")
                + 0.26366 * get("T23")
                - 424.72638 * f_ratio_4
            )

            # Температура 50% выкипания
            vak["24-2000:GODT:T50"] = (
                44.625 + 10.0224 * get("P13") + 0.06981 * get("F9") + 0.8052 * get("T6")
            )

            # Выход фракции до 250 °C (I250)
            vak["24-2000:GODT:I250"] = (
                84.585
                - 0.21172 * get("T5")
                + 0.12137 * get("T11")
                - 0.00014 * get("F25")
                + 0.56248 * get("F14")
                - 0.16317 * get("T23")
                + 0.20272 * get("T16")
            )

            # Авторегрессионная плотность D15 (по последнему анализу LIMS)
            lims_d15 = get("LIMS:24-2000.Pipeline.D15", 830.0)
            vak["24-2000:GODT:D15"] = (
                667.881 + 0.15417 * lims_d15 + 0.00005 * get("F22") + 0.10774 * get("T11")
            )

            # Авторегрессионная температура 95% выкипания (по LIMS)
            lims_t95 = get("LIMS:24-2000.Pipeline.95%.T", 340.0)
            vak["24-2000:GODT:T95"] = (
                0.03814 * get("F9")
                - 9.201
                - 0.00002 * get("F2")
                + 0.62259 * get("T6")
                + 0.48321 * lims_t95
            )

            # Температура помутнения (Cloud Point)
            vak["24-2000:GODT:CloudPoint"] = (
                get("F22")
                + 0.0021 * get("W7")
                + 0.00008 * get("F25")
                - 0.30656 * get("F1")
                + 0.12018 * get("T6")
                + 0.01916 * get("F9")
                - 48.254
                - 0.05249 * get("T16")
                + 0.00011
            )

            # Предельная температура фильтруемости (CFPP)
            vak["24-2000:GODT:CFPP"] = (
                0.22088 * get("T6")
                - 102.375
                - 47.75834 * get("P8")
                + 0.03862 * get("F9")
                + 43.60207 * get("W7")
                + 43.81849 * get("P24")
            )

            # Начало кипения (IBP)
            vak["24-2000:GODT:IBP"] = (
                137.762
                - 0.0653 * get("F26")
                + 0.00011 * get("F22")
                + 5.78137 * get("P13")
                - 34.58028 * get("P24")
                - 0.00993 * get("F14")
                - 0.99962 * get("W4")
                + 0.32232 * get("T23")
                - 0.09406 * get("T16")
            )
        except Exception:
            pass

        return vak
