"""Модуль виртуальных анализаторов качества (ВАК / Soft Sensors).

Реализует 17 расчетных моделей по официальным формулам из new_data/формулы_ВАК.xlsx
для оперативной оценки свойств потоков установок ЭЛОУ-АВТ-6 и 24-2000 (ADR-11).
Использует канонические теги AVT_* и HT_*, полученные через normalize_tags().
"""

from __future__ import annotations

import math
from typing import Any, Dict, Mapping

from src.twin.tags import normalize_tags


class VakCalculator:
    """
    Вычисление 17 виртуальных анализаторов качества (ВАК) на основе официальных формул.
    """

    @staticmethod
    def calculate(tags: Mapping[str, Any]) -> Dict[str, float]:
        """
        Рассчитывает 17 показателей качества по текущим значениям тегов.

        :param tags: Словарь тегов (сырых КИПиА, канонических или смешанных с LIMS).
        :return: Словарь расчетных параметров ВАК.
        """
        # 1. Приведение всех тегов к каноническим ключам
        norm_tags, _ = normalize_tags(tags)
        vak: Dict[str, float] = {}

        def get(tag_name: str, default: float = 0.0) -> float:
            """Безопасное извлечение значения: проверяет канонический, сырой или переданный ключ."""
            val = norm_tags.get(tag_name)
            if val is None or math.isnan(val) or math.isinf(val):
                # Пробуем сырой ключ из исходного словаря, если передан
                val = tags.get(tag_name)
            if val is None:
                return default
            try:
                num = float(val)
                return default if (math.isnan(num) or math.isinf(num)) else num
            except (ValueError, TypeError):
                return default

        # =========================================================================
        # 1. ЭЛОУ-АВТ-6: Фракция 240-350 °C (Дизельный дистиллят)
        # =========================================================================
        try:
            # 1.1. Плотность D15
            # Формула: 791.22872 − 5.30294*(F65/(F32+F30)) + 0.52755*T66 − 0.15629*T33
            f65 = get("AVT_F65", get("F65"))
            f30 = get("AVT_F30", get("F30"))
            f32 = get("AVT_F32", get("F32"))
            t66 = get("AVT_T66", get("T66"))
            t33 = get("AVT_T33", get("T33"))

            denom_diesel = f32 + f30
            f_ratio_diesel = f65 / denom_diesel if abs(denom_diesel) > 1e-9 else 0.0
            vak["AVT6:240-350:D15"] = (
                791.22872 - 5.30294 * f_ratio_diesel + 0.52755 * t66 - 0.15629 * t33
            )

            # 1.2. Температура 50% выкипания (T50)
            # 283.177 − 0.01685*F7 + 0.06248*F30 + 0.22048*F34 − 0.25816*F45 − 0.12159*F59 + 0.01221*F63
            vak["AVT6:240-350:T50"] = (
                283.177
                - 0.01685 * get("AVT_F7", get("F7"))
                + 0.06248 * f30
                + 0.22048 * get("AVT_F34", get("F34"))
                - 0.25816 * get("AVT_F45", get("F45"))
                - 0.12159 * get("AVT_F59", get("F59"))
                + 0.01221 * get("AVT_F63", get("F63"))
            )

            # 1.3. Конец кипения (EBP)
            # 813.883 + 2.66463*F30 − 0.20239*T33 − 3.65888*F36 − 14.08235*T37 − 1.32603*T40 + 14.60206*T58
            vak["AVT6:240-350:EBP"] = (
                813.883
                + 2.66463 * f30
                - 0.20239 * t33
                - 3.65888 * get("AVT_F36", get("F36"))
                - 14.08235 * get("AVT_T37", get("T37"))
                - 1.32603 * get("AVT_T40", get("T40"))
                + 14.60206 * get("AVT_T58", get("T58"))
            )

            # 1.4. Предельная температура фильтруемости (CFPP)
            # 31.40363 − 0.06784*T33 + 17.411*P67 − 8.11544*P4 − 0.47309*F65/(F32+F30)
            p67 = get("AVT_P67", get("P67"))
            p4 = get("AVT_P4", get("P4"))
            vak["AVT6:240-350:CFPP"] = (
                31.40363
                - 0.06784 * t33
                + 17.411 * p67
                - 8.11544 * p4
                - 0.47309 * f_ratio_diesel
            )
        except Exception:
            pass

        # =========================================================================
        # 2. ЭЛОУ-АВТ-6: Фракция >350 °C (Мазут / Гудрон / Вакуумный газойль)
        # =========================================================================
        try:
            f31 = get("AVT_F31", get("F31"))
            f57 = get("AVT_F57", get("F57"))
            f_ratio_f31_f57 = f31 / f57 if abs(f57) > 1e-9 else 0.0

            t42 = get("AVT_T42", get("T42"))
            t48 = get("AVT_T48", get("T48"))
            l43 = get("AVT_L43", get("L43"))
            avt_t6 = get("AVT_T6", get("T6"))
            avt_t18 = get("AVT_T18", get("T18"))

            # 2.1. Кинематическая вязкость ViscosityK (350-500)
            vak["AVT6:350-500:ViscosityK"] = (
                5.831
                + 0.00976 * avt_t6
                + 0.01188 * get("AVT_T13", get("T13"))
                + 0.00224 * avt_t18
                + 0.01905 * get("AVT_T20", get("T20"))
                + 0.00794 * l43
                - 0.02496 * t48
                - 0.00008 * get("AVT_P50", get("P50"))
                - 0.00882 * get("AVT_F53", get("F53"))
                - 0.00394 * get("AVT_P51", get("P51"))
                - 0.00255 * get("AVT_F59", get("F59"))
                + 0.01153 * get("AVT_T61", get("T61"))
            )

            # 2.2. Предельная температура фильтруемости CFPP (350)
            vak["AVT6:350:CFPP"] = (
                19.27111
                - 0.10582 * t48
                + 0.13836 * get("AVT_T40", get("T40"))
                - 0.42304 * f_ratio_f31_f57
            )

            # 2.3. Температура 50% выкипания T50 (350)
            # Официально: 493.6798 + 1.281193*T42 − 0.955342*T48 − 0.018454*F31 + 0.265904*F57 − 0.082047*T66 − 0.545083*T33
            vak["AVT6:350:T50"] = (
                493.6798
                + 1.281193 * t42
                - 0.955342 * t48
                - 0.018454 * f31
                + 0.265904 * f57
                - 0.082047 * get("AVT_T66", get("T66"))
                - 0.545083 * get("AVT_T33", get("T33"))
            )

            # 2.4. Выход фракции I350 (350)
            # Официально: 39.562 − 1.62865*L43 + 0.76664*T6 − 0.22361*T18 + 0.00031*F64*(T15−T11)
            t15 = get("AVT_T15", get("T15"))
            t11 = get("AVT_T11", get("T11"))
            f64 = get("AVT_F64", get("F64"))
            vak["AVT6:350:I350"] = (
                39.562
                - 1.62865 * l43
                + 0.76664 * avt_t6
                - 0.22361 * avt_t18
                + 0.00031 * f64 * (t15 - t11)
            )

            # 2.5. Плотность D15 (350)
            # Официально: 983.092 + 0.27467*T42 − 0.49014*T48 − 0.32983*F31/F57
            vak["AVT6:350:D15"] = (
                983.092
                + 0.27467 * t42
                - 0.49014 * t48
                - 0.32983 * f_ratio_f31_f57
            )
        except Exception:
            pass

        # =========================================================================
        # 3. Установка 24-2000: Стабильный гидрогенизат (ГО ДТ)
        # =========================================================================
        try:
            f1 = get("HT_F1", get("F1"))
            f26 = get("HT_F26", get("F26"))
            f_ratio_f1_f26 = f1 / f26 if abs(f26) > 1e-9 else 0.0

            ht_t6 = get("HT_T6", get("T6"))
            ht_t11 = get("HT_T11", get("T11"))
            ht_t12 = get("HT_T12", get("T12"))
            ht_t16 = get("HT_T16", get("T16"))
            ht_t23 = get("HT_T23", get("T23"))
            ht_f9 = get("HT_F9", get("F9"))
            ht_f14 = get("HT_F14", get("F14"))
            ht_f15 = get("HT_F15", get("F15"))
            ht_f22 = get("HT_F22", get("F22"))
            ht_f25 = get("HT_F25", get("F25"))
            ht_w7 = get("HT_W7", get("W7"))
            ht_p8 = get("HT_P8", get("P8"))
            ht_p13 = get("HT_P13", get("P13"))
            ht_p24 = get("HT_P24", get("P24"))

            # 3.1. Температура 90% выкипания (T90)
            # Официально: 162.998 + 0.12945*T12 + 59.57*(F15/2000) + 0.00036*W7 + 0.26366*T23 − 424.72638*F1/F26
            vak["24-2000:GODT:T90"] = (
                162.998
                + 0.12945 * ht_t12
                + 59.57 * (ht_f15 / 2000.0)
                + 0.00036 * ht_w7
                + 0.26366 * ht_t23
                - 424.72638 * f_ratio_f1_f26
            )

            # 3.2. Температура 50% выкипания (T50)
            # Официально: 44.625 + 10.0224*P13 + 0.06981*F9 + 0.471*T6
            vak["24-2000:GODT:T50"] = (
                44.625
                + 10.0224 * ht_p13
                + 0.06981 * ht_f9
                + 0.471 * ht_t6
            )

            # 3.3. Выход фракции до 250 °C (I250)
            # 84.585 − 0.21172*T5 + 0.12137*T11 − 0.00014*F25 + 0.56248*F14 − 0.16317*T23 + 0.20272*T16
            t5 = get("HT_T5", get("T5"))
            vak["24-2000:GODT:I250"] = (
                84.585
                - 0.21172 * t5
                + 0.12137 * ht_t11
                - 0.00014 * ht_f25
                + 0.56248 * ht_f14
                - 0.16317 * ht_t23
                + 0.20272 * ht_t16
            )

            # 3.4. Авторегрессионная плотность D15 (по последнему анализу LIMS)
            # 667.881 + 0.15417*LIMS.D15 + 0.00005*F22 + 0.10774*T11
            lims_d15 = get("LIMS:24-2000.Pipeline.D15", get("LIMS.D15", 840.0))
            vak["24-2000:GODT:D15"] = (
                667.881 + 0.15417 * lims_d15 + 0.00005 * ht_f22 + 0.10774 * ht_t11
            )

            # 3.5. Авторегрессионная температура 95% выкипания (по LIMS)
            # Официально: 0.03814*F9 − 9.201 − 0.00002*F2 + 0.50*T6 + 0.48321*LIMS.95%.T
            lims_t95 = get("LIMS:24-2000.Pipeline.95%.T", get("LIMS.95%.T", 347.5))
            f2 = get("HT_F2", get("F2"))
            vak["24-2000:GODT:T95"] = (
                0.03814 * ht_f9
                - 9.201
                - 0.00002 * f2
                + 0.50 * ht_t6
                + 0.48321 * lims_t95
            )

            # 3.6. Температура помутнения (Cloud Point)
            # Официально: 0.0002*F22 + 0.0021*W7 + 0.00008*F25 − 0.30656*F1 + 0.12018*T6 + 0.01916*F9 − 48.254 − 0.05249*T16 + 0.00011
            vak["24-2000:GODT:CloudPoint"] = (
                0.0002 * ht_f22
                + 0.0021 * ht_w7
                + 0.00008 * ht_f25
                - 0.30656 * f1
                + 0.12018 * ht_t6
                + 0.01916 * ht_f9
                - 48.254
                - 0.05249 * ht_t16
                + 0.00011
            )

            # 3.7. Предельная температура фильтруемости (CFPP)
            # Официально: 0.22088*T23 − 102.375 − 47.75834*P8 + 0.03862*F9 + 43.60207*W7 + 43.81849*P24
            vak["24-2000:GODT:CFPP"] = (
                0.22088 * ht_t23
                - 102.375
                - 47.75834 * ht_p8
                + 0.03862 * ht_f9
                + 43.60207 * ht_w7
                + 43.81849 * ht_p24
            )

            # 3.8. Начало кипения (IBP)
            # 137.762 − 0.0653*F26 + 0.00011*F22 + 5.78137*P13 − 34.58028*P24 − 0.00993*F14 − 0.99962*W4 + 0.32232*T23 − 0.09406*T16
            w4 = get("HT_W4", get("W4"))
            vak["24-2000:GODT:IBP"] = (
                137.762
                - 0.0653 * f26
                + 0.00011 * ht_f22
                + 5.78137 * ht_p13
                - 34.58028 * ht_p24
                - 0.00993 * ht_f14
                - 0.99962 * w4
                + 0.32232 * ht_t23
                - 0.09406 * ht_t16
            )
        except Exception:
            pass

        return vak


